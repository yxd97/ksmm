"""Generate and build the ksmm-cuda torch extension: fp16, batch last (bs_last), batch = 25088, sm_86.

The kernels are ksmm's own templates (src/ksmm_py/layer/kronecker_sparse/template_kernels_half.cuh,
included read-only). Hyperparameters come only from kernel_bs_last_half.best rows with batch 25088;
there is no fallback search (kernel.py:171-173 picks configs without looking at the batch). Nothing
under src/ is written: kernel.py:247-284 would rewrite the tracked .cuh, so this script generates its
own dispatch table instead.

The kernel template parameters are (VSIZE, TILEX, TILEK, TILEY, TX, TY); a, b, c, d are run-time
arguments. So one compilation unit per distinct parameter set compiles every kernel, and a table in
binding.cpp maps each (a, b, c, d) to its launcher. Every launch goes on the current CUDA stream.

  build.py --out DIR [--limit N] [--jobs J]   generate DIR/src and build DIR/build/ksmm_cuda_bsl_half.so
  build.py --covered CHAINS_CSV               print the chains whose stages all have hyperparameters,
                                              comma-separated (for gpu_bench.py --only); stdlib only

Build environment: CUDA_HOME is the toolkit (nvcc) to use; see README.md.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # ksmm repository root
KS = ROOT / "src" / "ksmm_py" / "layer" / "kronecker_sparse"
BEST = KS / "kernel_bs_last_half.best"
TEMPLATE = KS / "template_kernels_half.cuh"
BATCH = 25088
ARCH = "8.6"  # RTX A6000
NAME = "ksmm_cuda_bsl_half"


def read_best() -> dict[tuple, tuple]:
    """(a, b, c, d) -> (TILEX, TILEK, TILEY, TX, TY, VSIZE) for batch BATCH; duplicate rows must agree."""
    table: dict[tuple, tuple] = {}
    lines = BEST.read_text(encoding="utf-8").splitlines()
    for line in lines[1:]:  # header: batch_size a b c d TILEX TILEK TILEY TX TY VSIZE ms std mse
        f = line.split()
        if not f or int(f[0]) != BATCH:
            continue
        key, hp = tuple(map(int, f[1:5])), tuple(map(int, f[5:11]))
        if table.setdefault(key, hp) != hp:
            raise ValueError(f"{BEST.name}: conflicting rows for batch {BATCH} pattern {key}: {table[key]} and {hp}")
    return table


def kernel_call(hp: tuple) -> str:
    """Template instance, as kernel.py:28-35 writes it for half."""
    tilex, tilek, tiley, tx, ty, vsize = hp
    if vsize == 4:
        return f"kernel_bs_last_half4<bool, {tilex}, {tilek}, {tiley}, {tx}, {ty}, 4, false, {tilex // tx}>"
    if vsize == 2:
        return f"kernel_bs_last_half2<half2, {tilex}, {tilek}, {tiley}, {tx}, {ty}, 2, true, {tilex // tx}>"
    raise ValueError(f"VSIZE {vsize}")


LAUNCH_SIG = ("void ksmm_launch_{k}(half *x, half *w, half *y, int batch, int a, int b, int c, int d, "
              "cudaStream_t stream)")


def unit_source(k: int, hp: tuple) -> str:
    tilex, _tilek, tiley, tx, ty, _vsize = hp
    return f"""// generated by ksmm bench/ksmm_cuda/build.py; config {k}: TILEX TILEK TILEY TX TY VSIZE = {hp}
#include "template_kernels_half.cuh"

{LAUNCH_SIG.format(k=k)} {{
  dim3 block({(tilex // tx) * (tiley // ty)});
  dim3 grid((a * b * d + {tilex} - 1) / {tilex}, (batch + {tiley} - 1) / {tiley});
  {kernel_call(hp)}<<<grid, block, 0, stream>>>(x, w, batch, y, a, b, c, d);
}}
"""


def binding_source(table: dict[tuple, tuple], cfg_id: dict[tuple, int]) -> str:
    decls = "\n".join(LAUNCH_SIG.format(k=k) + ";" for k in sorted(cfg_id.values()))
    rows = "\n".join(
        f'    {{{{{a}, {b}, {c}, {d}}}, {{ksmm_launch_{cfg_id[hp]}, "{"x".join(map(str, hp[:3]))}/t{hp[3]}x{hp[4]}/v{hp[5]}"}}}},'
        for (a, b, c, d), hp in sorted(table.items()))
    return f"""// generated by ksmm bench/ksmm_cuda/build.py: dispatch table of ksmm's bs_last fp16 kernels,
// hyperparameters of {BEST.name} for batch {BATCH} only ({len(table)} patterns, {len(cfg_id)} kernel configs).
#include <torch/extension.h>
#include <c10/cuda/CUDAException.h>
#include <c10/cuda/CUDAStream.h>
#include <cuda_fp16.h>
#include <array>
#include <map>
#include <string>

{decls}

using Launch = void (*)(half *, half *, half *, int, int, int, int, int, cudaStream_t);
struct Entry {{
  Launch launch;
  const char *config;  // TILEXxTILEKxTILEY/tTXxTY/vVSIZE
}};
static const std::map<std::array<int, 4>, Entry> TABLE = {{
{rows}
}};
static constexpr int BATCH = {BATCH};

static const Entry &entry(int a, int b, int c, int d) {{
  auto it = TABLE.find({{a, b, c, d}});
  TORCH_CHECK(it != TABLE.end(), "no batch-", BATCH, " bs_last half hyperparameters for (", a, ",", b, ",", c, ",", d, ")");
  return it->second;
}}

// y (a*b*d, batch) = pattern (a, b, c, d) applied to x (a*c*d, batch); w is the kernel layout
// (a*d*c, b) = W.permute(0, 3, 2, 1). Launched on the current stream (CUDA graph capture works).
torch::Tensor forward(torch::Tensor x, torch::Tensor w, int64_t a, int64_t b, int64_t c, int64_t d) {{
  const Entry &e = entry(a, b, c, d);
  TORCH_CHECK(x.is_cuda() && w.is_cuda() && x.scalar_type() == torch::kHalf && w.scalar_type() == torch::kHalf,
              "x and w must be CUDA fp16");
  TORCH_CHECK(x.is_contiguous() && w.is_contiguous(), "x and w must be contiguous");
  TORCH_CHECK(x.dim() == 2 && x.size(0) == a * c * d && x.size(1) == BATCH, "x must be (a*c*d, ", BATCH, ")");
  TORCH_CHECK(w.numel() == a * b * c * d, "w must have a*b*c*d elements");
  auto y = torch::empty({{a * b * d, BATCH}}, x.options());
  e.launch(reinterpret_cast<half *>(x.data_ptr()), reinterpret_cast<half *>(w.data_ptr()),
           reinterpret_cast<half *>(y.data_ptr()), BATCH, a, b, c, d, c10::cuda::getCurrentCUDAStream());
  C10_CUDA_KERNEL_LAUNCH_CHECK();
  return y;
}}

std::string config(int64_t a, int64_t b, int64_t c, int64_t d) {{ return entry(a, b, c, d).config; }}

bool has(int64_t a, int64_t b, int64_t c, int64_t d) {{ return TABLE.count({{(int)a, (int)b, (int)c, (int)d}}) > 0; }}

PYBIND11_MODULE(TORCH_EXTENSION_NAME, m) {{
  m.def("forward", &forward, "ksmm bs_last fp16 kernel, batch {BATCH}, on the current CUDA stream");
  m.def("config", &config, "TILEXxTILEKxTILEY/tTXxTY/vVSIZE of a pattern");
  m.def("has", &has, "whether a pattern has hyperparameters");
  m.attr("batch") = BATCH;
}}
"""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(out: Path, limit: int | None) -> tuple[list[Path], dict]:
    table = read_best()
    if limit:
        table = dict(list(table.items())[:limit])  # file order; for the compile-time estimate
    cfg_id: dict[tuple, int] = {}
    for hp in table.values():
        cfg_id.setdefault(hp, len(cfg_id))
    src = out / "src"
    src.mkdir(parents=True, exist_ok=True)
    sources = [src / "binding.cpp"]
    sources[0].write_text(binding_source(table, cfg_id), encoding="utf-8")
    for hp, k in cfg_id.items():
        path = src / f"cfg{k:02d}.cu"
        path.write_text(unit_source(k, hp), encoding="utf-8")
        sources.append(path)
    info = {"patterns": len(table), "kernel_configs": len(cfg_id), "batch": BATCH, "arch": ARCH,
            "best": str(BEST.relative_to(ROOT)), "best_sha256": sha256(BEST),
            "template": str(TEMPLATE.relative_to(ROOT)), "template_sha256": sha256(TEMPLATE)}
    return sources, info


def build(out: Path, limit: int | None, jobs: int) -> None:
    sources, info = generate(out, limit)
    cuda_home = os.environ["CUDA_HOME"]
    os.environ["TORCH_CUDA_ARCH_LIST"] = ARCH  # torch emits -gencode for sm_86 only; no GPU query
    os.environ["MAX_JOBS"] = str(jobs)
    os.environ["PATH"] = f"{cuda_home}/bin:{os.environ['PATH']}"
    import torch
    from torch.utils.cpp_extension import load

    nvcc = subprocess.run([f"{cuda_home}/bin/nvcc", "--version"], capture_output=True, text=True,
                          check=True).stdout.strip().splitlines()[-2:]
    build_dir = out / "build"
    build_dir.mkdir(parents=True, exist_ok=True)
    t0 = time.perf_counter()
    load(name=NAME, sources=[str(s) for s in sources], build_directory=str(build_dir),
         extra_cuda_cflags=[f"-I{KS}"], verbose=True)
    seconds = time.perf_counter() - t0
    info.update(built_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), build_s=round(seconds, 1),
                jobs=jobs, cuda_home=cuda_home, nvcc=nvcc, torch=torch.__version__, torch_cuda=torch.version.cuda,
                so=str(build_dir / f"{NAME}.so"))
    (out / "manifest.json").write_text(json.dumps(info, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(info), flush=True)


def covered(chains_csv: Path) -> list[str]:
    table = read_best()
    names = []
    with open(chains_csv, encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            stages, k = [], 0
            while row.get(f"A{k}"):
                stages.append(tuple(int(row[f"{x}{k}"]) for x in "ABCD"))
                k += 1
            if all(s in table for s in stages):
                names.append(row["chain"])
    return names


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", type=Path, help="build directory (generated sources, ninja build, .so, manifest.json)")
    p.add_argument("--limit", type=int, help="only the first N patterns of the table (compile-time estimate)")
    p.add_argument("--jobs", type=int, default=8, help="parallel compile jobs (MAX_JOBS)")
    p.add_argument("--covered", type=Path, help="chains.csv: print the covered chain names, comma-separated")
    args = p.parse_args()
    if args.covered:
        names = covered(args.covered)
        print(",".join(names))
        print(f"{len(names)} chains covered", file=sys.stderr)
    elif args.out:
        build(args.out, args.limit, args.jobs)
    else:
        p.error("give --out or --covered")


if __name__ == "__main__":
    main()
